<#
.SYNOPSIS
  Convert a JSON module profile into addon\AzerothKit\Profile.lua (the agent's
  write channel into the game), bump its version, and validate the addon.

.NOTES
  ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less .ps1 files as
  ANSI, which mangles non-ASCII literals.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\ak-config.ps1
  powershell -ExecutionPolicy Bypass -File tools\ak-config.ps1 -Json profiles\raid.json -Version 7
#>
[CmdletBinding()]
param(
    [string]$Json = 'profiles\default.json',
    [string]$Out = 'addon\AzerothKit\Profile.lua',
    [int]$Version = 0,
    [switch]$NoCheck
)

$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot

function Resolve-RepoPath([string]$p) {
    if ([System.IO.Path]::IsPathRooted($p)) { return $p }
    return (Join-Path $repo $p)
}

$jsonPath = Resolve-RepoPath $Json
$outPath = Resolve-RepoPath $Out

if (-not (Test-Path -LiteralPath $jsonPath)) {
    throw "JSON not found: $jsonPath"
}

function Format-LuaString([string]$s) {
    $e = $s.Replace('\', '\\').Replace('"', '\"').Replace("`r", '').Replace("`n", '\n').Replace("`t", '\t')
    return '"' + $e + '"'
}

function Format-LuaKey([string]$k) {
    if ($k -match '^[A-Za-z_][A-Za-z0-9_]*$') { return $k }
    return '[' + (Format-LuaString $k) + ']'
}

function Format-LuaValue {
    param($Value, [string]$Indent = '')

    if ($null -eq $Value) { return 'nil' }
    if ($Value -is [bool]) { if ($Value) { return 'true' } else { return 'false' } }
    if ($Value -is [string]) { return (Format-LuaString $Value) }

    if ($Value -is [int] -or $Value -is [long] -or $Value -is [double] -or $Value -is [single] -or $Value -is [decimal]) {
        return ([double]$Value).ToString('R', [System.Globalization.CultureInfo]::InvariantCulture)
    }

    $inner = $Indent + '    '

    if ($Value -is [System.Collections.IDictionary]) {
        $keys = @($Value.Keys) | Sort-Object
        if ($keys.Count -eq 0) { return '{}' }
        $lines = foreach ($k in $keys) {
            $inner + (Format-LuaKey ([string]$k)) + ' = ' + (Format-LuaValue $Value[$k] $inner) + ','
        }
        return "{`n" + ($lines -join "`n") + "`n" + $Indent + '}'
    }

    if ($Value -is [System.Collections.IEnumerable]) {
        $items = @($Value)
        if ($items.Count -eq 0) { return '{}' }
        $lines = foreach ($it in $items) { $inner + (Format-LuaValue $it $inner) + ',' }
        return "{`n" + ($lines -join "`n") + "`n" + $Indent + '}'
    }

    $names = @($Value.PSObject.Properties | ForEach-Object { $_.Name }) | Sort-Object
    if ($names.Count -eq 0) { return '{}' }
    $lines = foreach ($n in $names) {
        $inner + (Format-LuaKey $n) + ' = ' + (Format-LuaValue $Value.$n $inner) + ','
    }
    return "{`n" + ($lines -join "`n") + "`n" + $Indent + '}'
}

$profile = Get-Content -LiteralPath $jsonPath -Raw | ConvertFrom-Json
if (-not $profile -or -not $profile.modules) { throw "JSON has no modules object: $jsonPath" }

# ---- version: explicit, or current + 1 ----
$current = 0
if (Test-Path -LiteralPath $outPath) {
    $hit = Select-String -LiteralPath $outPath -Pattern 'version\s*=\s*(\d+)' | Select-Object -First 1
    if ($hit) { $current = [int]$hit.Matches[0].Groups[1].Value }
}
$newVersion = if ($Version -gt 0) { $Version } else { $current + 1 }

$doc = [ordered]@{
    version = $newVersion
    modules = $profile.modules
}

$lua = Format-LuaValue $doc ''

$header = @(
    '-- Profile.lua - agent write channel (fixed name, always listed in the TOC)'
    ('-- generated by tools/ak-config.ps1; source: ' + $Json)
    '-- applied only when version > AzerothKitDB.appliedProfile; /reload to apply'
)

$content = ($header -join "`n") + "`nAzerothKitProfile = " + $lua + "`n"
$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText($outPath, $content, $utf8)

Write-Host ("Profile written: {0}" -f $outPath) -ForegroundColor Green
Write-Host ("  version = {0}" -f $newVersion)
Write-Host ("  source  = {0}" -f $jsonPath)

if (-not $NoCheck) {
    $check = Join-Path $PSScriptRoot 'check.ps1'
    if (Test-Path -LiteralPath $check) {
        & powershell -NoProfile -ExecutionPolicy Bypass -File $check
        $code = $LASTEXITCODE
        if ($code -ne 0) {
            Write-Host 'check.ps1 reported errors' -ForegroundColor Red
            exit $code
        }
    }
}

exit 0

